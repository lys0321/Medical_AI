def curated(concept_id):
    """返回该知识点人工校对的出处条目；没有维护的返回空表。"""
    out = []
    for code, page, anchor, label in PAGES.get(concept_id) or []:
        book = BOOKS.get(code)
        if not book:
            continue
        out.append({"book": book, "page": page, "anchor": anchor, "label": label})
    return out